function generateGuideMarkdown(guide: BankGuide): string {
  const lines: string[] = [];

  lines.push("## 申请方式");
  lines.push("");
  lines.push(`> **目标：** 只要你有一部智能手机和一张${guide.name}储蓄卡，按照下面的步骤操作，就能在线完成贷款申请。`);

  // Preparation checklist
  lines.push("");
  lines.push("### 准备清单（操作前核对）");
  lines.push("");
  lines.push("在开始之前，请确认你准备好了以下东西：");
  lines.push("");
  lines.push(`- [ ] 一部智能手机（能上网、能收短信）`);
  lines.push(`- [ ] 一张 **${guide.name}储蓄卡**（也叫借记卡，就是存钱的卡）`);
  lines.push(`- [ ] 你的**身份证**（申请时要填身份证号码）`);
  lines.push("");
  lines.push(`如果你还没有${guide.name}储蓄卡，带上身份证去任意一家${guide.name}网点，跟工作人员说"我要办一张储蓄卡"，很快就能办好。`);
  lines.push("");

  // Steps
  guide.steps.forEach((step: StepGuide, idx: number) => {
    lines.push("---");
    lines.push("");
    lines.push(`### 第${['一','二','三','四','五','六','七','八'][idx] || (idx+1)}步：${step.title}`);
    lines.push("");

    if (step.diagram) {
      lines.push("```");
      lines.push(step.diagram.trim());
      lines.push("```");
      lines.push("");
    }

    lines.push("**操作步骤：**");
    lines.push("");
    step.instructions.forEach((inst: string, i: number) => {
      lines.push(`${i + 1}. ${inst}`);
    });
    lines.push("");

    if (step.tips && step.tips.length > 0) {
      step.tips.forEach((tip: string) => {
        lines.push(`> 💡 **提示：** ${tip}`);
      });
      lines.push("");
    }
  });

  // Important reminders
  lines.push("---");
  lines.push("");
  lines.push("### ⚠️ 重要提醒");
  lines.push("");
  lines.push("| 事项 | 说明 |");
  lines.push("|------|------|");
  guide.tips.forEach((tip: string) => {
    const parts = tip.split("，");
    const first = parts[0] + "，";
    const rest = parts.slice(1).join("，");
    lines.push(`| **${first}** | ${rest} |`);
  });
  lines.push(`| **遇到问题** | 拨打${guide.name}客服 **${guide.customerService}**，跟客服说你在哪一步卡住了 |`);
  lines.push("");

  return lines.join("\n");
}

