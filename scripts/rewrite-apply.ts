// Main: Read products, generate guides, update intro_html
// ============================================================

import { Pool } from "pg";

async function main() {
  const pool = new Pool({ connectionString: "postgresql://Z1858@localhost:5432/yinmaiquan" });

  const args = process.argv.slice(2);
  const dryRun = args.includes("--dry-run");

  // Get all products
  const r = await pool.query("SELECT id, name, institution, intro_html, category FROM products ORDER BY id");
  const products = r.rows;
  console.log(`Found ${products.length} products`);

  let updated = 0;
  let skipped = 0;

  for (const p of products) {
    const oldIntro = p.intro_html || "";

    // Find the existing "## 申请方式" section
    const applyMatch = oldIntro.match(/## 申请方式[\s\S]*?(?=## |$)/);

    if (!applyMatch) {
      skipped++;
      continue;
    }

    // Generate new apply guide
    const guide = findGuide(p);
    const newApplySection = generateGuideMarkdown(guide);

    // Replace old apply section with new one
    const newIntro = oldIntro.replace(applyMatch[0], newApplySection);

    if (!dryRun) {
      await pool.query("UPDATE products SET intro_html = $1 WHERE id = $2", [newIntro, p.id]);
    }
    updated++;
    if (updated % 50 === 0) console.log(`  ${updated}/${products.length} done`);
  }

  console.log(`\nDone. Updated: ${updated}, Skipped (no apply section): ${skipped}`);
  if (dryRun) console.log("DRY RUN - no database changes made.");

  await pool.end();
}

main().catch(err => { console.error(err); process.exit(1); });
